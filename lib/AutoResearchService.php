<?php

declare(strict_types=1);

require_once __DIR__ . '/BacktestEngine.php';
require_once __DIR__ . '/StrategyVersionService.php';
require_once __DIR__ . '/StrategyRuleParser.php';
require_once __DIR__ . '/AI/Gateway/LLMGateway.php';

final class AutoResearchService
{
    private const RUNS_FILE = 'research/auto_research_runs.json';

    public function __construct(
        private JsonStore $store,
        private StrategyVersionService $versions,
        private BacktestEngine $backtests,
        private ?LLMGateway $llmGateway = null
    ) {
    }

    public function recentRuns(int $limit = 20): array
    {
        $runs = $this->store->readJson(self::RUNS_FILE, []);
        if (!is_array($runs)) {
            return [];
        }

        usort($runs, fn($a, $b) => strcmp((string)($b['createdAt'] ?? ''), (string)($a['createdAt'] ?? '')));
        return array_slice(array_values(array_filter($runs, 'is_array')), 0, max(1, min(100, $limit)));
    }

    public function run(array $payload): array
    {
        $symbol = strtoupper(trim((string)($payload['symbol'] ?? '')));
        if ($symbol === '') {
            throw new InvalidArgumentException('Bạn chưa chọn cặp tiền để AI Research tự backtest.');
        }

        $mode = $this->normalizeMode((string)($payload['mode'] ?? $payload['researchMode'] ?? 'optimize_existing'));
        $baseVersion = $mode === 'from_zero'
            ? $this->discoveryBaseVersion($symbol)
            : $this->baseVersion((string)($payload['strategyVersionId'] ?? ''));
        $defaultRounds = $mode === 'from_zero' ? 12 : 6;
        $maxRounds = max(1, min(50, (int)($payload['maxRounds'] ?? $defaultRounds)));
        $maxSeconds = max(30, min(3600, (int)($payload['maxSeconds'] ?? 300)));
        $startedAt = gmdate('c');
        $deadline = microtime(true) + $maxSeconds;
        $kpi = $this->normalizeKpi(is_array($payload['kpi'] ?? null) ? $payload['kpi'] : []);
        $settings = $this->normalizeSettings(is_array($payload['settings'] ?? null) ? $payload['settings'] : []);
        $aiProvider = $this->normalizeAiProvider((string)($payload['aiProvider'] ?? $payload['ai_provider'] ?? 'internal'));
        $methodProfile = $this->normalizeMethodProfile((string)($payload['methodProfile'] ?? $payload['method_profile'] ?? 'h4_trend_zone_m15_pa'));

        $baseRules = StrategyRuleParser::normalize(is_array($baseVersion['rulesJson'] ?? null) ? $baseVersion['rulesJson'] : []);
        if (!in_array($symbol, $baseRules['symbols'], true)) {
            $baseRules['symbols'][] = $symbol;
        }
        if ($mode === 'from_zero') {
            $baseVersion = $this->discoveryBaseVersion($symbol, $methodProfile);
            $baseRules = StrategyRuleParser::normalize(is_array($baseVersion['rulesJson'] ?? null) ? $baseVersion['rulesJson'] : []);
        }
        $aiPlan = $this->buildAiResearchPlan($aiProvider, $symbol, $mode, $kpi, $baseRules, $methodProfile);

        $rounds = [];
        $best = null;
        $previous = null;
        $seen = [];
        $status = 'FAILED';
        $stopReason = 'Đã chạy hết số vòng cho phép nhưng chưa đạt KPI.';

        for ($round = 1; $round <= $maxRounds; $round++) {
            if (microtime(true) >= $deadline) {
                $status = 'TIME_LIMIT';
                $stopReason = 'Đã hết giới hạn thời gian chạy research.';
                break;
            }

            $candidate = $this->candidateRules($baseRules, $round, $best, $previous, $mode, $symbol, $aiPlan, $kpi);
            $hash = sha1(json_encode($candidate['rules'], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: (string)$round);
            if (isset($seen[$hash])) {
                $candidate = $mode === 'from_zero'
                    ? $this->adaptiveDiscoveryCandidate($baseRules, $round, $best, $previous, $symbol, $kpi, true)
                    : $this->adaptiveCandidate($baseRules, $round, $best, $previous, true, $kpi);
                $hash = sha1(json_encode($candidate['rules'], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: (string)$round);
            }
            $seen[$hash] = true;

            $virtualVersion = [
                'id' => (string)($baseVersion['id'] ?? 'base') . '_research_round_' . $round,
                'name' => $candidate['name'],
                'parentVersionId' => $baseVersion['id'] ?? null,
                'createdAt' => gmdate('c'),
                'createdBy' => 'ai',
                'status' => 'draft',
                'rulesJson' => $candidate['rules'],
                'notes' => 'Virtual candidate generated by one-click AI Research. No live trading.',
            ];

            $result = $this->backtests->run($virtualVersion, [
                'symbol' => $symbol,
                'dataSplit' => 'full',
                'initialBalance' => $settings['initialBalance'],
                'spreadPoints' => $settings['spreadPoints'],
                'feeR' => $settings['feeR'],
                'slippagePoints' => $settings['slippagePoints'],
                'maxBarsInTrade' => $settings['maxBarsInTrade'],
                'rulesPreset' => 'current',
                'debugLevel' => 0,
                'persist' => false,
            ]);
            $summary = is_array($result['summary'] ?? null) ? $result['summary'] : $result;
            $evaluation = $this->evaluateSummary($summary, $kpi);

            $record = [
                'round' => $round,
                'candidateName' => $candidate['name'],
                'strategyFamily' => (string)($candidate['family'] ?? ''),
                'parentRound' => $candidate['parentRound'] ?? null,
                'optimizationFocus' => (string)($candidate['optimizationFocus'] ?? ''),
                'changes' => $candidate['changes'],
                'summary' => $this->compactSummary($summary),
                'diagnostics' => $this->compactDiagnostics(is_array($summary['diagnostics'] ?? null) ? $summary['diagnostics'] : []),
                'kpiPassed' => $evaluation['passed'],
                'score' => $evaluation['score'],
                'failReasons' => $evaluation['failReasons'],
                'trades' => $this->compactTrades(is_array($result['trades'] ?? null) ? $result['trades'] : []),
                'rulesJson' => $candidate['rules'],
            ];
            $rounds[] = $record;
            $previous = $record;

            if ($best === null || (float)$record['score'] > (float)$best['score']) {
                $best = $record;
            }

            if ($evaluation['passed']) {
                $status = 'PASSED';
                $stopReason = 'Đã tìm được bộ quy tắc đạt KPI.';
                break;
            }
        }

        $bestVersion = null;
        if ($best !== null) {
            $bestNotes = $mode === 'from_zero'
                ? 'Created by AI Strategy Discovery from zero. This is still research only, not live trading approval.'
                : 'Created by one-click AI Research. This is still research only, not live trading approval.';
            $bestVersion = $mode === 'from_zero'
                ? $this->versions->createRootFromRules(
                    $this->bestVersionName($symbol, $status, $mode),
                    'ai',
                    $bestNotes,
                    $best['rulesJson'],
                    $this->sourceTextForDiscovery($symbol, $best)
                )
                : $this->versions->createFromParent(
                    (string)$baseVersion['id'],
                    $this->bestVersionName($symbol, $status, $mode),
                    'ai',
                    $bestNotes,
                    $best['rulesJson']
                );
            $bestVersion = $this->versions->attachBacktestSummary((string)$bestVersion['id'], $best['summary']) ?? $bestVersion;
            if ($status === 'PASSED') {
                $bestVersion = $this->versions->updateStatus((string)$bestVersion['id'], 'final_test_passed', 'AI Research KPI passed on full historical backtest. Human review is still required.');
            }
        }

        $run = [
            'id' => 'research_' . gmdate('Ymd_His') . '_' . bin2hex(random_bytes(4)),
            'mode' => $mode,
            'symbol' => $symbol,
            'status' => $status,
            'stopReason' => $stopReason,
            'baseStrategyVersionId' => (string)($baseVersion['id'] ?? ''),
            'bestStrategyVersionId' => (string)($bestVersion['id'] ?? ''),
            'kpi' => $kpi,
            'settings' => $settings,
            'aiProvider' => $aiProvider,
            'methodProfile' => $methodProfile,
            'methodProfileLabel' => $this->methodProfileLabel($methodProfile),
            'aiPlan' => $aiPlan,
            'maxRounds' => $maxRounds,
            'maxSeconds' => $maxSeconds,
            'roundsRun' => count($rounds),
            'bestCandidate' => $best ? $this->withoutRules($best) : null,
            'rounds' => array_map(fn(array $round): array => $this->withoutRules($round), $rounds),
            'safety' => [
                'liveTrading' => false,
                'mt5OrderExecution' => false,
                'usesFullHistoricalData' => true,
                'createsBestResearchVersionOnly' => true,
            ],
            'createdAt' => $startedAt,
            'completedAt' => gmdate('c'),
        ];
        $this->persistRun($run);

        return [
            'ok' => true,
            'research_run' => $run,
            'best_strategy_version' => $bestVersion,
            'auto_research_runs' => $this->recentRuns(20),
        ];
    }

    private function baseVersion(string $requestedId): array
    {
        if ($requestedId !== '') {
            $version = $this->versions->find($requestedId);
            if ($version === null) {
                throw new InvalidArgumentException('Không tìm thấy phiên bản chiến lược gốc cho AI Research.');
            }
            return $version;
        }

        $versions = $this->versions->list();
        if ($versions !== []) {
            return $versions[0];
        }

        return $this->versions->createFromCurrentStrategy(
            $this->store->readJson('strategy.json', []),
            $this->store->readJson('strategy_summary.json', []),
            $this->store->readJson('accounts.json', [])
        );
    }

    private function normalizeMode(string $mode): string
    {
        $mode = strtolower(trim($mode));
        return in_array($mode, ['from_zero', 'optimize_existing'], true) ? $mode : 'optimize_existing';
    }

    private function normalizeAiProvider(string $provider): string
    {
        $provider = strtolower(trim($provider));
        return $provider === 'openai_chat' ? 'openai_chat' : 'internal';
    }

    private function normalizeMethodProfile(string $methodProfile): string
    {
        $methodProfile = strtolower(trim($methodProfile));
        $allowed = [
            'h4_trend_zone_m15_pa' => true,
            'pa_sd_h4_m15' => true,
            'liquidity_sweep_pa' => true,
            'trend_pullback' => true,
            'range_sd_reversal' => true,
            'free_explore' => true,
        ];

        return isset($allowed[$methodProfile]) ? $methodProfile : 'h4_trend_zone_m15_pa';
    }

    private function methodProfileLabel(string $methodProfile): string
    {
        return match ($this->normalizeMethodProfile($methodProfile)) {
            'h4_trend_zone_m15_pa' => 'H4 Trend + H4 Zone + M15 Price Action',
            'pa_sd_h4_m15' => 'Price Action + Vùng canh buy/sell H4/M15',
            'liquidity_sweep_pa' => 'Liquidity sweep / false break',
            'trend_pullback' => 'Pullback theo xu hướng',
            'range_sd_reversal' => 'Range trading tại vùng canh buy/sell',
            'free_explore' => 'Tự do khám phá nhiều họ chiến lược',
            default => 'H4 Trend + H4 Zone + M15 Price Action',
        };
    }

    private function buildAiResearchPlan(string $provider, string $symbol, string $mode, array $kpi, array $baseRules, string $methodProfile = 'h4_trend_zone_m15_pa'): ?array
