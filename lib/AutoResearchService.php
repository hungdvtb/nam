    private function bestDirectionFromTrades(array $trades): string
    {
        $stats = [
            'BUY' => ['count' => 0, 'r' => 0.0],
            'SELL' => ['count' => 0, 'r' => 0.0],
        ];

        foreach ($trades as $trade) {
            if (!is_array($trade)) {
                continue;
            }
            $direction = strtoupper((string)($trade['direction'] ?? ''));
            if (!isset($stats[$direction])) {
                continue;
            }
            $stats[$direction]['count']++;
            $stats[$direction]['r'] += (float)($trade['netR'] ?? $trade['rrResult'] ?? 0);
        }

        $buyCount = $stats['BUY']['count'];
        $sellCount = $stats['SELL']['count'];
        if ($buyCount < 3 && $sellCount < 3) {
            return 'BUY_SELL';
        }

        $buyExpectancy = $buyCount > 0 ? $stats['BUY']['r'] / $buyCount : -999.0;
        $sellExpectancy = $sellCount > 0 ? $stats['SELL']['r'] / $sellCount : -999.0;
        if ($buyCount >= 3 && ($sellCount < 3 || $buyExpectancy > $sellExpectancy + 0.08)) {
            return 'BUY';
        }
        if ($sellCount >= 3 && ($buyCount < 3 || $sellExpectancy > $buyExpectancy + 0.08)) {
            return 'SELL';
        }

        return 'BUY_SELL';
    }

