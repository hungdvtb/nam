        if ($provider !== 'openai_chat') {
            return null;
        }
        if ($this->llmGateway === null) {
            throw new RuntimeException('OpenAI provider đã được chọn nhưng LLM Gateway chưa được cấu hình cho AutoResearch.');
        }

        $allowed = $mode === 'from_zero' ? $this->discoveryFamilies() : $this->optimizationFamilies();
        $response = $this->llmGateway->call([
            'task_type' => 'strategy_proposal',
            'agent_role' => 'StrategyAI',
            'prompt_template_key' => 'strategy.idea.generate',
            'preferred_provider' => 'openai_chat',
            'output_format' => 'json_object',
            'variables' => [
                'research_goal' => 'Chọn tối đa 3 hướng nghiên cứu từ allowed_families. Chỉ trả JSON: {"families":["..."],"reason":"..."}. Khóa phương pháp mẹ: H4 xác định xu hướng/sóng và vùng supply-demand/support-resistance; chỉ ưu tiên BUY tại demand/support thuận H4 hoặc SELL tại supply/resistance thuận H4; khi giá về vùng H4 mới xuống M15 tìm Price Action đảo chiều như rejection wick, engulfing, liquidity sweep hoặc CHoCH/BOS rồi mới tạo lệnh. AI chỉ được tối ưu tham số trong khung này, không đổi sang indicator/scalping/random method. Không bịa kết quả backtest. Không đề xuất đặt lệnh live.',
                'strategy_context' => json_encode([
                    'symbol' => $symbol,
                    'mode' => $mode,
                    'method_profile' => $this->methodProfileLabel($methodProfile),
                    'method_blueprint' => 'Khóa phương pháp mẹ: H4 xác định xu hướng/sóng và vùng supply-demand/support-resistance; chỉ ưu tiên BUY tại demand/support thuận H4 hoặc SELL tại supply/resistance thuận H4; khi giá về vùng H4 mới xuống M15 tìm Price Action đảo chiều như rejection wick, engulfing, liquidity sweep hoặc CHoCH/BOS rồi mới tạo lệnh. AI chỉ được tối ưu tham số trong khung này, không đổi sang indicator/scalping/random method.',
                    'kpi' => $kpi,
                    'allowed_families' => array_keys($allowed),
                    'base_rules_summary' => [
                        'minRR' => $baseRules['minRR'] ?? null,
                        'directionAllowed' => $baseRules['directionAllowed'] ?? null,
                        'h4MinZoneStrength' => $baseRules['h4Rules']['minZoneStrength'] ?? null,
                        'm15RequireStructureBreak' => $baseRules['m15Rules']['requireStructureBreak'] ?? null,
                        'm15RequirePriceActionPattern' => $baseRules['m15Rules']['requirePriceActionPattern'] ?? null,
                        'm15AllowedPriceActionPatterns' => $baseRules['m15Rules']['allowedPriceActionPatterns'] ?? null,
                    ],
                ], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
                'memory_lessons' => 'Backtest/KPI phải do app tính. OpenAI chỉ chọn hướng thử từ allowed_families trong khung phương pháp mẹ.',
            ],
            'metadata' => [
                'auto_research' => true,
                'live_trading' => false,
            ],
        ])->toArray();

        if (($response['ok'] ?? false) !== true) {
            $message = is_array($response['error'] ?? null) ? (string)($response['error']['message'] ?? '') : '';
            throw new RuntimeException($message !== '' ? $message : 'OpenAI không trả được kế hoạch research.');
        }

        $parsed = is_array($response['parsed'] ?? null) ? $response['parsed'] : [];
        $families = is_array($parsed['families'] ?? null) ? $parsed['families'] : [];
        if ($families === [] && isset($parsed['family'])) {
            $families = [$parsed['family']];
        }
        $families = array_values(array_filter(array_map(
            fn(mixed $family): string => strtolower(trim((string)$family)),
            $families
        ), fn(string $family): bool => isset($allowed[$family])));

        if ($families === []) {
            $families = [array_key_first($allowed)];
        }

        return [
            'provider' => 'openai_chat',
            'families' => array_slice(array_values(array_unique($families)), 0, 3),
            'reason' => (string)($parsed['reason'] ?? 'OpenAI chọn hướng nghiên cứu từ danh sách an toàn.'),
            'llm' => [
                'provider' => $response['provider'] ?? null,
                'model' => $response['model_name'] ?? null,
                'cost' => $response['cost'] ?? null,
                'usage' => $response['usage'] ?? null,
            ],
        ];
    }

