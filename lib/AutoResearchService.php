                . number_format((float)($summary['averageRR'] ?? 0), 2) . ' average RR, '
                . number_format((float)($summary['profitFactor'] ?? 0), 2) . ' PF, '
                . number_format((float)($summary['maxDrawdownPercent'] ?? 0), 2) . '% max drawdown, '
                . (int)($summary['totalTrades'] ?? 0) . ' trades.',
            'Safety: research only, no MT5 order execution.',
        ]));
    }

    private function persistRun(array $run): void
    {
        $runs = $this->store->readJson(self::RUNS_FILE, []);
        if (!is_array($runs)) {
            $runs = [];
        }
        array_unshift($runs, $run);
        $this->store->writeJson(self::RUNS_FILE, array_slice($runs, 0, 100));
    }

    private function getPath(array $target, array $parts, mixed $fallback = null): mixed
    {
        foreach ($parts as $part) {
            if (!is_array($target) || !array_key_exists($part, $target)) {
                return $fallback;
            }
            $target = $target[$part];
        }
        return $target;
    }

    private function setPath(array &$target, array $parts, mixed $value): void
    {
        $key = array_shift($parts);
        if ($key === null || $key === '') {
            return;
        }
        if ($parts === []) {
            $target[$key] = $value;
            return;
        }
        if (!isset($target[$key]) || !is_array($target[$key])) {
            $target[$key] = [];
        }
        $this->setPath($target[$key], $parts, $value);
    }
