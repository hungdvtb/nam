    private function normalizeKpi(array $payload): array
    {
        return [
            'winRateMin' => max(0, min(100, (float)($payload['winRateMin'] ?? $payload['win_rate_min'] ?? 50))),
            'averageRRMin' => max(0.1, (float)($payload['averageRRMin'] ?? $payload['average_rr_min'] ?? 2.0)),
            'profitFactorMin' => max(0, (float)($payload['profitFactorMin'] ?? $payload['profit_factor_min'] ?? 1.5)),
            'maxDrawdownMax' => max(0, (float)($payload['maxDrawdownMax'] ?? $payload['max_drawdown_max'] ?? 10)),
            'totalTradesMin' => max(1, (int)($payload['totalTradesMin'] ?? $payload['total_trades_min'] ?? 30)),
            'netProfitPercentMin' => (float)($payload['netProfitPercentMin'] ?? $payload['net_profit_percent_min'] ?? 0),
        ];
    }

    private function normalizeSettings(array $payload): array
    {
        $spread = $payload['spreadPoints'] ?? $payload['spread_points'] ?? null;
        return [
            'initialBalance' => max(1, (float)($payload['initialBalance'] ?? $payload['initial_balance'] ?? 10000)),
            'spreadPoints' => $spread === '' ? null : $spread,
            'feeR' => max(0, (float)($payload['feeR'] ?? $payload['fee_r'] ?? 0.02)),
            'slippagePoints' => max(0, (float)($payload['slippagePoints'] ?? $payload['slippage_points'] ?? 2)),
            'maxBarsInTrade' => max(5, (int)($payload['maxBarsInTrade'] ?? $payload['max_bars_in_trade'] ?? 96)),
        ];
    }

    private function candidateRules(array $baseRules, int $round, ?array $best, ?array $previous, string $mode, string $symbol, ?array $aiPlan = null, array $kpi = []): array
    {
        if ($mode === 'from_zero') {
            return $this->discoveryCandidate($baseRules, $round, $best, $previous, $symbol, $aiPlan, $kpi);
        }

        return $this->optimizationCandidate($baseRules, $round, $best, $previous, $aiPlan, $kpi);
    }

    private function discoveryCandidate(array $baseRules, int $round, ?array $best, ?array $previous, string $symbol, ?array $aiPlan = null, array $kpi = []): array
    {
        if ($round > 3) {
            return $this->adaptiveDiscoveryCandidate($baseRules, $round, $best, $previous, $symbol, $kpi);
        }

        $rules = StrategyRuleParser::normalize($baseRules);
        $rules['symbols'] = [$symbol];
        $changes = [];
        $family = $this->plannedFamilyForRound($aiPlan, $round, 'from_zero') ?? match ($round) {
            1 => 'h4_zone_m15_structure_balanced',
            2 => 'h4_zone_quality_filter',
            3 => 'h4_zone_loose_sample_finder',
            4 => 'h4_zone_strong_rr3',
            5 => 'buy_only_demand',
            6 => 'sell_only_supply',
            7 => 'zone_extreme_entry',
            8 => 'zone_midpoint_entry',
            9 => 'longer_zone_lifecycle',
            default => 'adaptive',
        };
        $name = 'AI tự tìm ' . $symbol . ' - ' . $this->familyLabel($family);

        $apply = function (string $path, mixed $value, string $reason) use (&$rules, &$changes): void {
            $old = $this->getPath($rules, explode('.', $path));
            $this->setPath($rules, explode('.', $path), $value);
            $changes[] = [
                'field' => $path,
                'oldValue' => $old,
                'newValue' => $value,
                'reason' => $reason,
            ];
        };

        $changes[] = [
            'field' => 'strategyFamily',
            'oldValue' => null,
            'newValue' => $family,
            'reason' => $aiPlan ? 'OpenAI chọn hướng nghiên cứu từ danh sách an toàn; app vẫn tự backtest toàn bộ dữ liệu.' : 'AI nội bộ tạo giả thuyết chiến lược từ số 0 rồi backtest toàn bộ dữ liệu.',
        ];

        $this->applyDiscoveryFamily($family, $apply);

        return [
            'name' => $name,
            'family' => $family,
            'parentRound' => null,
            'optimizationFocus' => $round === 1
                ? 'Vòng lấy mẫu ban đầu: đo chiến lược cân bằng trước khi tối ưu.'
                : 'Vòng lấy mẫu ban đầu: thử một hướng khác để có dữ liệu so sánh.',
            'rules' => StrategyRuleParser::normalize($rules),
            'changes' => $changes,
        ];
    }

    private function optimizationCandidate(array $baseRules, int $round, ?array $best, ?array $previous, ?array $aiPlan = null, array $kpi = []): array
    {
        $rules = $round <= 6 ? $baseRules : (is_array($best['rulesJson'] ?? null) ? $best['rulesJson'] : $baseRules);
        $changes = [];
        $name = 'AI Research round ' . $round;

        $apply = function (string $path, mixed $value, string $reason) use (&$rules, &$changes): void {
            $old = $this->getPath($rules, explode('.', $path));
            $this->setPath($rules, explode('.', $path), $value);
            $changes[] = [
                'field' => $path,
                'oldValue' => $old,
                'newValue' => $value,
                'reason' => $reason,
            ];
        };

        $plannedFamily = $this->plannedFamilyForRound($aiPlan, $round, 'optimize_existing');
        if ($plannedFamily !== null) {
            $changes[] = ['field' => 'aiPlan', 'oldValue' => null, 'newValue' => $plannedFamily, 'reason' => 'OpenAI chọn hướng tối ưu từ danh sách an toàn.'];
            $this->applyOptimizationFamily($plannedFamily, $apply, $name);
        } else {
            match ($round) {
            1 => $changes[] = ['field' => 'baseline', 'oldValue' => null, 'newValue' => 'current_rules', 'reason' => 'Chạy full historical backtest với luật hiện tại trước.'],
            2 => $this->loosenSampleCandidate($apply, $name),
            3 => $this->rrTwoBalancedCandidate($apply, $name),
            4 => $this->qualityCandidate($apply, $name),
            5 => $this->longerPendingCandidate($apply, $name),
            6 => $this->activeZoneCandidate($apply, $name),
            default => null,
            };
        }

        if ($round > 6) {
            return $this->adaptiveCandidate($rules, $round, $best, $previous, false, $kpi);
        }

        $rules = StrategyRuleParser::normalize($rules);
        return [
            'name' => $name,
            'family' => 'optimize_existing',
            'parentRound' => $round > 1 ? (int)($best['round'] ?? 0) : null,
            'optimizationFocus' => 'Tối ưu bản chiến lược có sẵn bằng một biến thể an toàn rồi so với KPI.',
            'rules' => $rules,
            'changes' => $changes,
        ];
    }

    private function adaptiveDiscoveryCandidate(array $baseRules, int $round, ?array $best, ?array $previous, string $symbol, array $kpi, bool $forceUnique = false): array
    {
        $source = is_array($best['rulesJson'] ?? null)
            ? $best['rulesJson']
            : (is_array($previous['rulesJson'] ?? null) ? $previous['rulesJson'] : $baseRules);
        $rules = StrategyRuleParser::normalize($source);
        $rules['symbols'] = [$symbol];
        $changes = [];
        $bestSummary = is_array($best['summary'] ?? null) ? $best['summary'] : [];
        $previousSummary = is_array($previous['summary'] ?? null) ? $previous['summary'] : [];
        $summary = $bestSummary !== [] ? $bestSummary : $previousSummary;
        $previousDiagnostics = is_array($previous['diagnostics'] ?? null) ? $previous['diagnostics'] : [];
        $previousTrades = is_array($previous['trades'] ?? null) ? $previous['trades'] : [];
        $bestTrades = is_array($best['trades'] ?? null) ? $best['trades'] : [];
        $trades = $bestTrades !== [] ? $bestTrades : $previousTrades;
        $failReasons = array_values(array_filter(array_map(
            'strval',
            is_array($previous['failReasons'] ?? null) ? $previous['failReasons'] : []
        )));

        $totalTrades = (int)($summary['totalTrades'] ?? 0);
        $winRate = (float)($summary['winRate'] ?? 0);
        $averageRr = (float)($summary['averageRR'] ?? 0);
        $profitFactor = (float)($summary['profitFactor'] ?? 0);
        $netProfit = (float)($summary['netProfitPercent'] ?? 0);
        $drawdown = (float)($summary['maxDrawdownPercent'] ?? 0);
        $tradeTarget = max(1, (int)($kpi['totalTradesMin'] ?? 30));
        $winTarget = (float)($kpi['winRateMin'] ?? 50);
        $rrTarget = (float)($kpi['averageRRMin'] ?? 2.0);
        $pfTarget = (float)($kpi['profitFactorMin'] ?? 1.5);
        $ddLimit = (float)($kpi['maxDrawdownMax'] ?? 10);
        $topSkippedReason = (string)($previousDiagnostics['topSkippedReason'] ?? '');
        $directionEdge = $this->bestDirectionFromTrades($trades);
        $family = 'adaptive_fast_explore';
        $focus = 'Chưa có lỗi trội rõ, AI đổi một vài tham số quanh bản tốt nhất để tránh lặp.';
        $name = 'AI tự tìm ' . $symbol . ' - tối ưu nhanh theo KPI';

        $apply = function (string $path, mixed $value, string $reason) use (&$rules, &$changes): void {
            $old = $this->getPath($rules, explode('.', $path));
            $this->setPath($rules, explode('.', $path), $value);
            $changes[] = [
                'field' => $path,
                'oldValue' => $old,
                'newValue' => $value,
                'reason' => $reason,
            ];
        };

        $sampleFloor = max(8, (int)ceil($tradeTarget * 0.7));
        if ($totalTrades < $sampleFloor || in_array('Số lệnh chưa đủ KPI.', $failReasons, true)) {
            $family = 'adaptive_fast_sample';
            $focus = 'Vòng tốt nhất mới có ' . $totalTrades . '/' . $tradeTarget . ' lệnh, nên AI nới điều kiện để lấy thêm mẫu trước.';
            $name .= ' - tăng số mẫu';
            $this->applyRr($apply, max(2.0, min(2.5, $rrTarget)), 'Giữ RR tối thiểu theo KPI nhưng không đặt quá cao khi đang thiếu mẫu.');
            $currentStrength = (float)$this->getPath($rules, ['h4Rules', 'minZoneStrength'], 60);
            $apply('h4Rules.minZoneStrength', max(35, $currentStrength - 10 - ($round % 2) * 5), 'Thiếu số lệnh, hạ ngưỡng sức mạnh vùng H4 để có thêm setup.');
            $apply('h4Rules.requireBosForZone', false, 'Không bắt BOS ở H4 khi đang cần đo đủ mẫu.');
            $apply('h4Rules.maxZoneTouches', min(14, max(8, (int)$this->getPath($rules, ['h4Rules', 'maxZoneTouches'], 6) + 2)), 'Cho vùng được test nhiều lần hơn để không bỏ mẫu quá sớm.');
            $apply('m15Rules.requireStructureBreak', $topSkippedReason === 'NO_M15_CONFIRMATION' ? false : (bool)$this->getPath($rules, ['m15Rules', 'requireStructureBreak'], false), 'Nếu thiếu xác nhận M15 nhiều, nới điều kiện này để đo mẫu.');
            $apply('m15Rules.avoidDirtySideway', false, 'Tắt lọc sideway quá chặt trong vòng tìm mẫu.');
            $apply('managementRules.cancelLimitAfterCandles', min(24, 12 + ($round % 4) * 3), 'Cho lệnh chờ thêm thời gian khớp.');
            $apply('entryRules.cancelLimitAfterCandles', min(24, 12 + ($round % 4) * 3), 'Đồng bộ thời gian hủy pending.');
            $apply('entryRules.entryAt', $round % 2 === 0 ? 'zone_50_percent' : 'zone_extreme_or_50_percent', 'Đổi vị trí entry để tăng xác suất khớp lệnh.');
        } elseif ($drawdown > $ddLimit) {
            $family = 'adaptive_fast_drawdown';
            $focus = 'Drawdown đang ' . number_format($drawdown, 2) . '% > KPI ' . number_format($ddLimit, 2) . '%, nên AI giảm rủi ro và siết vùng.';
            $name .= ' - giảm drawdown';
            $this->applyRr($apply, max(2.0, $rrTarget), 'Giữ RR tối thiểu trong khi giảm drawdown.');
            $apply('riskPercent', 0.5, 'Giảm rủi ro mỗi lệnh để đường vốn bớt sụt.');
            $apply('maxRiskPercent', 1.0, 'Giới hạn rủi ro tối đa trong vòng giảm drawdown.');
            $apply('directionAllowed', $directionEdge, $directionEdge === 'BUY_SELL' ? 'Chưa có chiều vượt trội rõ, giữ cả mua và bán.' : 'Chỉ giữ chiều có expectancy tốt hơn trong các lệnh đã backtest.');
            $apply('h4Rules.minZoneStrength', min(90, max(70, (float)$this->getPath($rules, ['h4Rules', 'minZoneStrength'], 65) + 10)), 'Tăng chất lượng vùng để giảm cụm thua.');
            $apply('h4Rules.requireBosForZone', true, 'Bắt vùng có BOS để giảm setup yếu.');
            $apply('m15Rules.requireStructureBreak', true, 'Bắt xác nhận M15 rõ hơn.');
            $apply('m15Rules.avoidDirtySideway', true, 'Tránh vùng đi ngang gây thua liên tiếp.');
        } elseif ($winRate < $winTarget || $profitFactor < $pfTarget || $netProfit < 0) {
            $family = 'adaptive_fast_quality';
            $focus = 'Đã có mẫu nhưng WR/PF/lợi nhuận thấp, nên AI siết chất lượng và ưu tiên chiều có thống kê tốt hơn.';
            $name .= ' - tăng chất lượng';
            $rr = max(2.0, min(2.5, $rrTarget));
            $this->applyRr($apply, $rr, 'Giữ RR vừa đủ để không làm winrate rơi thêm khi đang tối ưu chất lượng.');
            $apply('directionAllowed', $directionEdge, $directionEdge === 'BUY_SELL' ? 'Chưa đủ bằng chứng BUY hoặc SELL tốt hơn, giữ hai chiều.' : 'Chỉ giữ chiều đang có expectancy tốt hơn trong lịch sử lệnh.');
            $apply('h4Rules.minZoneStrength', min(88, max(65, (float)$this->getPath($rules, ['h4Rules', 'minZoneStrength'], 60) + 8)), 'WR/PF thấp, lọc vùng H4 mạnh hơn.');
            $apply('h4Rules.requireBosForZone', true, 'Bắt buộc vùng có phá cấu trúc để giảm setup yếu.');
            $apply('h4Rules.maxZoneTouches', max(2, min(5, (int)$this->getPath($rules, ['h4Rules', 'maxZoneTouches'], 6))), 'Loại vùng bị chạm quá nhiều.');
            $apply('m15Rules.requireStructureBreak', true, 'Cần xác nhận M15 rõ hơn để nâng xác suất.');
            $apply('m15Rules.avoidDirtySideway', true, 'Tránh tín hiệu nhiễu trong sideway.');
            $apply('entryRules.entryAt', 'zone_extreme', 'Entry sát biên vùng để giảm SL tương đối và lọc điểm vào.');
            $apply('managementRules.moveSlToBEAfterR', $round % 2 === 0 ? 1.5 : 1.8, 'Thử dời hòa vốn sau khi có lợi nhuận để giảm lệnh thắng thành thua.');
        } elseif ($averageRr < $rrTarget) {
            $family = 'adaptive_fast_rr';
            $focus = 'Average RR đang ' . number_format($averageRr, 2) . ' < KPI ' . number_format($rrTarget, 2) . ', nên AI chỉnh entry/TP để cải thiện R trung bình.';
            $name .= ' - cải thiện RR';
            $rr = max(2.0, min(3.0, $rrTarget + ($round % 2) * 0.25));
            $this->applyRr($apply, $rr, 'Nâng target RR sát KPI để cải thiện R trung bình.');
            $apply('entryRules.entryAt', 'zone_extreme', 'Entry sát biên vùng để SL ngắn hơn và RR tốt hơn.');
            $apply('entryRules.stopBufferPoints', max(1, 2 + ($round % 3)), 'Tinh chỉnh buffer SL để cân bằng giữa RR và nhiễu giá.');
            $apply('managementRules.moveSlToBEAfterR', max(1.8, min(2.5, $rr - 0.2)), 'Không dời hòa vốn quá sớm để giữ cơ hội đạt TP.');
        } else {
            $family = 'adaptive_fast_explore';
            $focus = 'Các KPI không lệch quá rõ, AI thử biến thể nhỏ quanh bản tốt nhất để tìm cải thiện.';
            $name .= ' - khám phá quanh bản tốt nhất';
            $rr = $round % 2 === 0 ? max(2.0, $rrTarget) : max(2.0, min(2.5, $rrTarget + 0.25));
            $this->applyRr($apply, $rr, 'Luân phiên RR gần KPI để so sánh expectancy.');
            $apply('h4Rules.minZoneStrength', max(45, min(85, 50 + (($round * 7) % 35))), 'Quét strength quanh bản tốt nhất để tránh mắc ở một cấu hình.');
            $apply('entryRules.entryAt', $round % 2 === 0 ? 'zone_extreme_or_50_percent' : 'zone_extreme', 'Luân phiên vị trí entry để đo ảnh hưởng lên WR/RR.');
        }

        if ($forceUnique) {
            $apply('entryRules.stopBufferPoints', 1 + ($round % 5), 'Thêm khác biệt nhỏ để tránh lặp candidate.');
            $focus .= ' Candidate trước bị trùng, nên AI thêm biến thể nhỏ để không test lại cùng luật.';
        }

        $changes[] = [
            'field' => 'optimizationFocus',
            'oldValue' => null,
            'newValue' => $focus,
            'reason' => 'Ghi lại mục tiêu tối ưu của vòng này để người dùng theo dõi.',
        ];

        return [
            'name' => $name,
            'family' => $family,
            'parentRound' => isset($best['round']) ? (int)$best['round'] : (isset($previous['round']) ? (int)$previous['round'] : null),
            'optimizationFocus' => $focus,
            'rules' => StrategyRuleParser::normalize($rules),
            'changes' => $changes,
        ];
    }

