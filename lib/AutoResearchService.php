    private function evaluateSummary(array $summary, array $kpi): array
    {
        $metrics = $this->compactSummary($summary);
        $failReasons = [];
        if ((int)$metrics['totalTrades'] < (int)$kpi['totalTradesMin']) {
            $failReasons[] = 'Số lệnh chưa đủ KPI.';
        }
        if ((float)$metrics['winRate'] < (float)$kpi['winRateMin']) {
            $failReasons[] = 'Winrate chưa đạt KPI.';
        }
        if ((float)$metrics['averageRR'] < (float)$kpi['averageRRMin']) {
            $failReasons[] = 'Average RR chưa đạt KPI.';
        }
        if ((float)$metrics['profitFactor'] < (float)$kpi['profitFactorMin']) {
            $failReasons[] = 'Profit factor chưa đạt KPI.';
        }
        if ((float)$metrics['maxDrawdownPercent'] > (float)$kpi['maxDrawdownMax']) {
            $failReasons[] = 'Max drawdown vượt KPI.';
        }
        if ((float)$metrics['netProfitPercent'] < (float)$kpi['netProfitPercentMin']) {
            $failReasons[] = 'Lợi nhuận ròng chưa đạt KPI.';
        }

        $score = (float)$metrics['netProfitPercent']
            + (float)$metrics['winRate'] * 0.5
            + (float)$metrics['averageRR'] * 15
            + (float)$metrics['profitFactor'] * 10
            + log(max(1, (int)$metrics['totalTrades'])) * 6
            - (float)$metrics['maxDrawdownPercent'] * 1.5
            - count($failReasons) * 12;

        return [
            'passed' => $failReasons === [],
            'score' => round($score, 4),
            'failReasons' => $failReasons,
        ];
    }

